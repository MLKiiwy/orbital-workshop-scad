#!/usr/bin/env python3
# Generate the MakerWorld (Parametric Model Maker) copy of a project's model.
# SPDX-License-Identifier: CC-BY-NC-SA-4.0
#
# Usage: scripts/makerworld.py projects/<name>/<name>.scad [--check]
#
# Reads projects/<name>/makerworld.json and writes
# projects/<name>/makerworld/<name>.scad: a single self-contained file that
# follows docs/makerworld-parametric.md:
#   - library includes rewritten from ../../libs/<lib>/... to <lib>/...
#     (MakerWorld only has its bundled libraries, at the top level; a model
#     using any other library, e.g. NopSCADlib or Round-Anything, is refused);
#   - the parameters listed under "hide" leave the Customizer: their lines
#     (and the comment lines just above them) are removed from the
#     Customizer sections and re-declared after /* [Hidden] */, optionally
#     with a new value; sections left empty are dropped;
#   - "replace" entries are applied verbatim (each must match exactly once).
# --check exits 1 if the generated file is missing or out of date.

import json
import re
import sys
from pathlib import Path

HIDDEN = "/* [Hidden] */"
SECTION = re.compile(r"^/\*\s*\[[^\]]+\]\s*\*/\s*$")
# Library directories MakerWorld bundles (docs/makerworld-parametric.md).
MAKERWORLD_LIBS = {"BOSL2", "threads-scad", "gridfinity-rebuilt-openscad", "KeyV2"}


def fail(msg):
    sys.exit(f"makerworld.py: {msg}")


def generate(src: Path, cfg: dict) -> str:
    lines = src.read_text().splitlines()
    try:
        hidden_at = lines.index(HIDDEN)
    except ValueError:
        fail(f"{src}: no '{HIDDEN}' line")

    head, tail = lines[:hidden_at], lines[hidden_at + 1:]
    hide = cfg.get("hide", {})
    fixed = []
    for name, value in hide.items():
        pat = re.compile(rf"^{re.escape(name)}\s*=\s*(.*?);")
        idx = [i for i, l in enumerate(head) if pat.match(l)]
        if len(idx) != 1:
            fail(f"parameter '{name}' found {len(idx)} times in the Customizer part")
        i = idx[0]
        original = pat.match(head[i]).group(1).strip()
        start = i
        while start > 0 and head[start - 1].lstrip().startswith("//") \
                and not SECTION.match(head[start - 1]):
            start -= 1
        del head[start:i + 1]
        fixed.append(f"{name} = {original if value is None else value};")

    # Drop Customizer sections left without parameters.
    out, i = [], 0
    while i < len(head):
        if SECTION.match(head[i]):
            j = i + 1
            while j < len(head) and not SECTION.match(head[j]):
                j += 1
            body = head[i + 1:j]
            if any(l.strip() and not l.lstrip().startswith("//") for l in body):
                out.extend(head[i:j])
            elif out and out[-1].strip() == "":
                pass  # avoid a double blank line where the section was
            i = j
        else:
            out.append(head[i])
            i += 1
    head = out

    banner = [
        "// MakerWorld Parametric Model Maker copy, GENERATED by",
        f"//   scripts/makerworld.py {src.as_posix()}",
        "// Do not edit: change the main model or makerworld.json and regenerate.",
        "// Rules followed: docs/makerworld-parametric.md",
    ]
    # Keep the mandatory two-line header first.
    text = "\n".join(head[:2] + banner + head[2:] + [HIDDEN]
                     + ["// Fixed for MakerWorld (not offered in the Customizer)"]
                     + fixed + tail) + "\n"

    text = re.sub(r"(include|use)\s*<(?:\.\./)+libs/", r"\1 <", text)
    for old, new in cfg.get("replace", []):
        n = text.count(old)
        if n != 1:
            fail(f"replace: {old!r} found {n} times")
        text = text.replace(old, new)

    if re.search(r"(include|use)\s*<\.", text):
        fail("a relative include/use is left; MakerWorld only takes one file")
    for lib in sorted(set(re.findall(r"(?:include|use)\s*<([^/>]+)/", text))):
        if lib not in MAKERWORLD_LIBS:
            fail(f"MakerWorld has no '{lib}' library (it only bundles "
                 f"{', '.join(sorted(MAKERWORLD_LIBS))}); see docs/makerworld-parametric.md")
    return text


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    if len(args) != 1:
        fail("usage: scripts/makerworld.py projects/<name>/<name>.scad [--check]")
    src = Path(args[0])
    cfg_path = src.parent / "makerworld.json"
    if not src.is_file() or not cfg_path.is_file():
        fail(f"need {src} and {cfg_path}")
    cfg = json.loads(cfg_path.read_text())
    dst = src.parent / "makerworld" / src.name
    text = generate(src, cfg)
    if check:
        if not dst.is_file() or dst.read_text() != text:
            fail(f"{dst} is out of date — run scripts/makerworld.py {src}")
        print(f"{dst} is up to date")
        return
    dst.parent.mkdir(exist_ok=True)
    dst.write_text(text)
    print(f"Wrote {dst}")


if __name__ == "__main__":
    main()
